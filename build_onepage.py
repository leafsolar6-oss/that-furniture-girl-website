#!/usr/bin/env python3
"""
build_onepage.py — bundles the multi-page site into ONE self-contained HTML file.

Why: the multi-page version in this folder is what you host (index.html,
shop.html, about.html, contact.html + assets). This script also produces
`that-furniture-girl-one-page.html`, a single file with every section, with the
CSS, JavaScript, fonts and photos embedded inside it — handy for previewing,
emailing, or dropping onto any host as one file.

Run it from the project folder:   python3 build_onepage.py
"""

import base64
import mimetypes
import pathlib
import re

ROOT = pathlib.Path(__file__).parent
OUT_NAME = "that-furniture-girl-one-page.html"

# The pages are generated by Astro into dist/ — run `npm run build` first
# (npm run onepage does both).
PAGES = [
    ("index.html",   "#home"),
]

BUILD = pathlib.Path("dist")

LINK_MAP = {
    "index.html":    "#home",
    "shop.html":     "#shop",
    # the single file has no separate products page — its grid is already on
    # the page, so "View products" just scrolls to it
    "products.html": "#collection",
    "products.html#cat-sofas":   "#collection",
    "products.html#cat-sets":    "#collection",
    "products.html#cat-tables":  "#collection",
    "products.html#cat-storage": "#collection",
    "about.html":    "#story",
    "contact.html":  "#visit",
    "index.html#custom": "#custom",
    "shop.html#cat-sofas": "#shop",
    "shop.html#cat-sets": "#shop",
    "shop.html#cat-tables": "#shop",
    "shop.html#cat-storage": "#shop",
}


def read(path):
    """Read a source file. HTML pages come from dist/ (Astro output)."""
    if str(path).endswith(".html"):
        return (ROOT / BUILD / path).read_text(encoding="utf-8")
    return (ROOT / path).read_text(encoding="utf-8")


def data_uri(path: pathlib.Path) -> str:
    mime = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    if path.suffix == ".woff2":
        mime = "font/woff2"
    b64 = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{b64}"


def inline_css() -> str:
    """Both stylesheets, concatenated in load order, fonts embedded."""
    css = read("public/assets/css/style.css")
    css += "\n" + read("public/assets/css/arrangement.css")
    for font in sorted((ROOT / "public" / "assets" / "fonts").glob("*.woff2")):
        rel = f"../fonts/{font.name}"
        css = css.replace(rel, data_uri(font))
    wm = ROOT / "public" / "assets" / "img" / "wm-144.webp"
    if wm.exists():
        css = css.replace("../img/wm-144.webp?v=3", data_uri(wm))
    return css


def extract_main(html: str) -> str:
    """Everything between the header/drawer and the footer."""
    m = re.search(r"<main\b[^>]*>(.*?)</main>", html, re.S)
    if m:
        return m.group(1).strip()
    # no <main> wrapper: take the body between </aside> and <footer
    body = re.search(r"<body[^>]*>(.*)</body>", html, re.S).group(1)
    body = body.split("</aside>", 1)[-1]
    body = body.split('<footer class="site-footer"')[0]
    return body.strip()


def rewrite_links(html: str) -> str:
    for src, dst in sorted(LINK_MAP.items(), key=lambda kv: -len(kv[0])):
        html = html.replace(f'href="{src}"', f'href="{dst}"')
    html = re.sub(r'\s+aria-current="page"', "", html)
    return html


def main() -> None:
    index_html = read("index.html")

    # ---- head / shell from index.html ----------------------------------
    head_meta = re.search(r"<head>(.*?)</head>", index_html, re.S).group(1)
    head_meta = re.sub(r"<title>.*?</title>", "", head_meta, flags=re.S)
    head_meta = re.sub(r'<link rel="stylesheet".*?>', "", head_meta, flags=re.S)
    head_meta = re.sub(r'<link rel="icon".*?>', "", head_meta, flags=re.S)

    title = ("<title>That Furniture Girl — Handcrafted Furniture in Ibadan, Nigeria"
             "</title>\n"
             '<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns=\'http://www.w3.org/2000/svg\' '
             "viewBox='0 0 32 32'%3E%3Crect width='32' height='32' rx='9' fill='%23004B1F'/%3E"
             "%3Cg fill='none' stroke='%23FFB600' stroke-width='1.7' stroke-linecap='round'%3E"
             "%3Cpath d='M8 17v-4.5A2.5 2.5 0 0 1 10.5 10h11A2.5 2.5 0 0 1 24 12.5V17'/%3E"
             "%3Cpath d='M6 18a2 2 0 0 1 2-2h16a2 2 0 0 1 2 2v3H6z'/%3E"
             "%3Cpath d='M9 21v2M23 21v2'/%3E%3C/g%3E%3C/svg%3E\">")
    # the theme-colour meta is read from index.html; keep it in step with --bg

    # ---- global chrome (announce / header / drawer / footer / fab) ------
    def block(start_pat, end_tag, count=1):
        """Pull one element out of the built page by its opening tag."""
        m = re.search(start_pat, index_html, re.S)
        if not m:
            raise SystemExit(f"could not find {start_pat} in the built page")
        # walk forward to the matching close tag
        i = m.start()
        depth = 0
        tag = re.match(r'<(\w+)', index_html[i:]).group(1)
        for tok in re.finditer(rf'<{tag}\b|</{tag}>', index_html[i:]):
            depth += 1 if tok.group(0).startswith(f'<{tag}') else -1
            if depth == 0:
                return index_html[i:i + tok.end()]
        raise SystemExit(f"unbalanced {tag} while extracting {start_pat}")

    announce = block(r'<div class="announce"', 'div')
    # the shared chrome also carries page links — rewrite them like any section,
    # otherwise the one-page file points at index.html / shop.html and 404s
    header = rewrite_links(block(r'<header class="site-header"', 'header'))
    scrim = block(r'<div class="scrim"', 'div')
    drawer = rewrite_links(block(r'<aside class="drawer"', 'aside'))
    chrome = scrim + "\n\n" + drawer
    footer = rewrite_links(block(r'<footer class="site-footer"', 'footer'))
    fab = rewrite_links(re.search(r'<a class="fab".*?</a>', index_html, re.S).group(0))
    search_panel = block(r'<div class="search-panel"', 'div')
    modal = block(r'<div class="modal" id="productModal"', 'div')

    # ---- sections ------------------------------------------------------
    sections = []
    for i, (page, anchor) in enumerate(PAGES):
        html = index_html if page == "index.html" else read(page)
        main_html = rewrite_links(extract_main(html))

        if i == 0:
            # give the hero an id so the nav can point at it
            main_html = main_html.replace('<section class="hero">', '<section class="hero" id="home">', 1)
            main_html = main_html.replace('<section class="section" id="collection">',
                                          '<section class="section section--tight" id="collection">', 1)
        else:
            marker = f'<span id="{anchor[1:]}"></span>'
            main_html = marker + "\n" + main_html
            # soften the inner-page hero blocks so they read as section dividers
            main_html = main_html.replace('class="page-hero page-hero--ink page-hero--media"',
                                          'class="page-hero page-hero--ink page-hero--media"', 1)

        sections.append(f"<!-- ============ {page} ============ -->\n{main_html}")

    # the bundled page only needs one modal + one scripts block
    body = "\n\n".join(sections)
    body = re.sub(r'<div class="modal" id="productModal"[^>]*>\s*</div>', "", body)
    # the search overlay + modal are part of the shared chrome: drop the copies
    # that came along with the page bodies
    body = re.sub(r'<div class="search-panel" id="searchPanel".*?</div>\s*</div>\s*</div>', "", body, flags=re.S)
    body = re.sub(r'<div class="modal" id="productModal".*?</div>', "", body, flags=re.S)
    body = re.sub(r'<noscript>.*?</noscript>', "", body, flags=re.S)

    # ---- photo map: lets the JS resolve product images without any files --
    products_src = read("src/data/products.js")
    photos = sorted(set(re.findall(r"img:\s*'([^']+)'", products_src)))
    img_map_entries = []
    for name in photos:
        photo = ROOT / "public" / "assets" / "img" / "opt" / name
        if photo.exists():
            img_map_entries.append(f'  "{name}": "{data_uri(photo)}"')
    img_map = "window.TFG_IMG_MAP = {\n" + ",\n".join(img_map_entries) + "\n};"

    # The bundle's interactive script was built by Astro as an ES module; the
    # one-pager has no module system, so hand it the data through window.TFG.
    bundled = sorted((ROOT / BUILD / "_astro").glob("Base.astro_astro_type_script*.js"))
    if not bundled:
        raise SystemExit("No bundled script in dist/_astro — run `npm run build` first.")
    app_js = bundled[0].read_text(encoding="utf-8")

    products_data = products_src
    products_data = products_data.replace("export const ", "const ")
    products_data = products_data.replace("export function ", "function ")
    products_data = products_data.replace("export { CONFIG, categoryLabel };", "")
    products_data += """
/* the one-page bundle has no module system: expose what the app script needs */
window.TFG = {
  CONFIG: CONFIG,
  PRODUCTS: PRODUCTS,
  CATEGORY_LABELS: CATEGORIES,
  TESTIMONIALS: TESTIMONIALS,
  categoryLabel: categoryLabel
};
"""

    out = f"""<!DOCTYPE html>
<html lang="en-NG">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
{title}
{head_meta.strip()}
<style>
/* ---- stylesheet, fonts embedded ---- */
{inline_css()}
</style>
</head>
<body>

{announce}

{header}

{chrome}

<main>

{body}

</main>

{footer}

{fab}

{search_panel}

{modal}

<script>
{img_map}
</script>
<script>
{products_data}
</script>
<script>
{app_js}
</script>
</body>
</html>
"""

    # ---- inline every photo and logo -------------------------------------
    def swap(match):
        rel = match.group(0)
        for base in (ROOT / "public", ROOT):
            path = base / rel
            if path.exists():
                return data_uri(path)
        return rel

    # photos used by the JS live in assets/img/opt/ and are mapped above;
    # everything else referenced directly in the markup gets embedded here
    # single-file build: drop webp <source> tags and srcset/sizes BEFORE inlining
    # so 480w/160w/800w variants never get embedded as duplicate data URIs
    out = re.sub(r'<source[^>]*type="image/webp"[^>]*>', '', out)
    out = re.sub(r'\s(?:srcset|sizes)="[^"]*"', '', out)
    out = re.sub(r"assets/img/(?!opt/)(?:[\w\-]+/)?[\w.\-]+\.(?:jpg|jpeg|png|webp)", swap, out)
    out = re.sub(r"assets/img/opt/[\w.\-]+\.jpg", swap, out)
    # the app script builds image paths at runtime ("assets/img/opt/" + p.img).
    # In this single file there are no image files, so route every one of them
    # through the embedded map instead — whatever variable it used.
    out = re.sub(r'"assets/img/opt/"\s*\+\s*([A-Za-z_$][\w$]*\.img)', r'window.TFG_IMG_MAP[\1]', out)
    out = re.sub(r"'assets/img/opt/'\s*\+\s*([A-Za-z_$][\w$]*\.img)", r'window.TFG_IMG_MAP[\1]', out)
    # ...including the paths built inside HTML template strings, like
    # '<img src="assets/img/opt/'+e.img+'" alt="...">'
    out = re.sub(r"assets/img/opt/'\s*\+\s*([A-Za-z_$][\w$]*\.img)\s*\+\s*'",
                 r"' + (window.TFG_IMG_MAP[\1] || '') + '", out)
    # Astro 7 minifies that same concatenation into template-literal form,
    # with the variable renamed:   "assets/img/opt/" `+e.img+`  ->  looks like
    #   src="assets/img/opt/`+e.img+`"
    out = re.sub(r"assets/img/opt/`\+([A-Za-z_$][\w$]*)\.img\+`",
                 r"`+window.TFG_IMG_MAP[\1.img]+`", out)
    # and the plain template form, in case a future minifier emits it
    out = re.sub(r"assets/img/opt/\$\{([A-Za-z_$][\w$]*\.img)\}",
                 r"${window.TFG_IMG_MAP[\1]||''}", out)

    # the self-contained file embeds JPEGs as data URIs; WebP <source> tags
    # would win selection and 404 offline, so drop them here.
    out = re.sub(r'<source[^>]*type="image/webp"[^>]*>', '', out)
    (ROOT / OUT_NAME).write_text(out, encoding="utf-8")
    size_mb = (ROOT / OUT_NAME).stat().st_size / 1024 / 1024
    real = re.findall(r'(?:src|href)="(assets/[^"]+)"', out)
    print(f"wrote {OUT_NAME}  ({size_mb:.2f} MB)")
    print("un-inlined asset references:", sorted(set(real)) or "none")
    print(f"photos embedded: {len(photos)}")


if __name__ == "__main__":
    main()
